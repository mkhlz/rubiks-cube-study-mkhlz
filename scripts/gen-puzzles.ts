/**
 * Generates src/data/puzzles-solve.ts: "solve in N" puzzles whose par is the
 * true optimal move count (half-turn metric). Random scrambles often cancel
 * down (R L R' is just L), so every candidate's distance is measured with a
 * meet-in-the-middle search: a table of every position within 4 moves of
 * solved, plus up to 3 moves of search from the puzzle. Seeded, so puzzle
 * ids (and saved progress) stay stable. Run with: npx tsx scripts/gen-puzzles.ts
 */
import { writeFileSync } from 'node:fs';
import { applyAlg, applyMoveMut, cloneState, CubeState, facelets, parseMove, solvedState } from '../src/cube/engine';
import { randomScramble } from '../src/cube/scramble';

const MOVES = ['U', 'D', 'R', 'L', 'F', 'B'].flatMap((f) => [f, `${f}'`, `${f}2`]).map(parseMove);

/** Positions within `depth` moves of solved, with their distance. */
function table(depth: number) {
  const dist = new Map<string, number>([[facelets(solvedState()), 0]]);
  let frontier: CubeState[] = [solvedState()];
  for (let d = 1; d <= depth; d++) {
    const next: CubeState[] = [];
    for (const s of frontier)
      for (const m of MOVES) {
        const t = cloneState(s);
        applyMoveMut(t, m);
        const k = facelets(t);
        if (!dist.has(k)) {
          dist.set(k, d);
          next.push(t);
        }
      }
    frontier = next;
  }
  return dist;
}

/** Optimal distance for positions up to 7 moves away, or -1 if further. */
export function optimal(s: CubeState, near: Map<string, number>): number {
  let best = near.get(facelets(s)) ?? Infinity;
  let frontier = [s];
  for (let k = 1; k <= 3 && k < best; k++) {
    const next: CubeState[] = [];
    for (const p of frontier)
      for (const m of MOVES) {
        const t = cloneState(p);
        applyMoveMut(t, m);
        const d = near.get(facelets(t));
        if (d !== undefined) best = Math.min(best, k + d);
        next.push(t);
      }
    frontier = next;
  }
  return Number.isFinite(best) ? best : -1;
}

/** Mulberry32: small seeded PRNG. */
function rng(seed: number) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t >>> 0) / 4294967296);
  };
}

if (process.argv[1]?.includes('gen-puzzles')) {
  const near = table(4);
  const rand = rng(20261022);
  const PER: Record<number, number> = { 1: 6, 2: 12, 3: 16, 4: 18, 5: 18, 6: 16, 7: 14 };
  const out: [number, string][] = [];
  const seen = new Set<string>();
  for (const [n, count] of Object.entries(PER).map(([a, b]) => [+a, b])) {
    let made = 0;
    while (made < count) {
      const scr = randomScramble(n, rand);
      const s = applyAlg(solvedState(), scr);
      const key = facelets(s);
      if (seen.has(key) || optimal(s, near) !== n) continue;
      seen.add(key);
      out.push([n, scr]);
      made++;
    }
  }
  const body = out.map(([n, s]) => `  [${n}, "${s}"],`).join('\n');
  writeFileSync(
    'src/data/puzzles-solve.ts',
    `// Generated by scripts/gen-puzzles.ts — do not edit by hand.\n/** [optimal moves (HTM), scramble] */\nexport const SOLVE_IN_N: [number, string][] = [\n${body}\n];\n`,
  );
  console.log(`wrote ${out.length} puzzles`);
}
